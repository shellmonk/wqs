-- Phase 5: the real source contract (spec 4.1; plan D1-D3).
--
-- D1: every projection table is emptied and the stream offset deleted, so the stream re-ingests
-- from offset 0. The phase-4 decoder could not parse a single real message, so the existing rows
-- are synthetic; rebuilding is cheaper and safer than converting counters in place. Dead letters
-- are kept: they hold the rejected real messages for audit.
truncate table
    "wqItemLocator", "wqWebItem", "wqCcItem", "wqGroupLocator", "wqSession", "wqPlay",
    "wqWebHighLevel", "wqCcHighLevel", "wqCountMonth", "wqCountDay", "wqPendingCancel";
delete from "wqStreamOffset";

-- The V9 covering indexes INCLUDE "productId"; they are rebuilt below on the new columns.
drop index "wqWebItem_cover";
drop index "wqCcItem_cover";
drop index "wqWebHighLevel_cover";
drop index "wqCcHighLevel_cover";

-- D3: products are strings on the wire ("productId" "TIKIKALACABANA", "productType" "instants"),
-- and the contract filters by product type. Both are stored on every row that had "productId";
-- the tables are empty, so the old ids convert to null. "wqProduct" has no remaining use: the
-- eInstant view is selected by product type (wqs.einstant.product-types).
alter table "wqWebItem"       alter column "productId" type text using null, add column "productType" text;
alter table "wqCcItem"        alter column "productId" type text using null, add column "productType" text;
alter table "wqSession"       alter column "productId" type text using null, add column "productType" text;
alter table "wqPlay"          alter column "productId" type text using null, add column "productType" text;
alter table "wqWebHighLevel"  alter column "productId" type text using null, add column "productType" text;
alter table "wqCcHighLevel"   alter column "productId" type text using null, add column "productType" text;
-- A parked cancel is rebuilt as the ProjectionItem that arrived, so it carries both too.
alter table "wqPendingCancel" alter column "productId" type text using null, add column "productType" text;

drop table "wqProduct";

-- Counters are re-keyed on (productType, typeId). Sentinels: "productType" = '' is ALL product
-- types, "typeId" = 0 is ALL transaction types. '' is unreachable from input (every blank is
-- normalised to null at the domain boundary) and real "wqTxType" ids start at 1. Rows are sparse
-- and mutable in place, as in V7 (spec 5.7).
drop table "wqCountMonth";
drop table "wqCountDay";

create table "wqCountMonth" (
    "userId"            bigint   not null,
    "viewKind"          smallint not null,  -- 1 = WEB, 2 = CC
    "pageUnit"          smallint not null,  -- 0 = ITEM (L0), 1 = HIGH_LEVEL (L1/L2)
    "productType"       text     not null,  -- '' = ALL product types
    "typeId"            smallint not null,  -- 0 = ALL transaction types
    "period"            date     not null,  -- first day of the month, UTC
    "cntAll"            bigint   not null default 0,
    "cntExclCancelled"  bigint   not null default 0,
    check ("cntAll" >= 0 and "cntExclCancelled" >= 0 and "cntExclCancelled" <= "cntAll"),
    primary key ("userId", "viewKind", "pageUnit", "productType", "typeId", "period")
);

-- Still monthly RANGE-partitioned on "period". Dropping the old table dropped its partitions;
-- the application's provisioning (PartitionManager, which checks every partitioned table
-- separately) recreates them on demand and at the rollover job's next run.
create table "wqCountDay" (
    "userId"            bigint   not null,
    "viewKind"          smallint not null,
    "pageUnit"          smallint not null,
    "productType"       text     not null,
    "typeId"            smallint not null,
    "period"            date     not null,
    "cntAll"            bigint   not null default 0,
    "cntExclCancelled"  bigint   not null default 0,
    check ("cntAll" >= 0 and "cntExclCancelled" >= 0 and "cntExclCancelled" <= "cntAll"),
    primary key ("userId", "viewKind", "pageUnit", "productType", "typeId", "period")
) partition by range ("period");

-- D2: transaction types are data, not code. "type" on item rows holds a "typeId". Seeded with
-- every type listed for walAccountTransactions.transactionType (docs/reference/source-schema.sql),
-- ids in the order listed there. An unseen code at ingest is inserted as NEUTRAL -- projected,
-- never dead-lettered. Polled-source type codes (payment, adjustment and limit types) live here
-- too. "direction": 0 = NEUTRAL, 1 = PLAY (counts towards totalPlays), 2 = WIN (totalWins).
-- Undo and rollback types stay NEUTRAL until decided otherwise.
create table "wqTxType" (
    "typeId"    smallint generated by default as identity primary key,
    "code"      text     not null unique,
    "direction" smallint not null default 0,
    check ("typeId" >= 1),
    check ("direction" in (0, 1, 2))
);

